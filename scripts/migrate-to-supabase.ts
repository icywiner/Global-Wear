import postgres from 'postgres';
import { createClient } from '@supabase/supabase-js';
import { offers, products } from '../src/data/products.ts';

const supabaseUrl = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.VITE_SUPABASE_URL;
const serviceRoleKey = process.env.SUPABASE_SECRET_KEY || process.env.SUPABASE_SERVICE_ROLE_KEY;
const databaseUrl = process.env.SUPABASE_DB_URL;

if (!supabaseUrl || !serviceRoleKey || !databaseUrl) {
  console.error('Faltan variables requeridas: SUPABASE_SECRET_KEY/SUPABASE_SERVICE_ROLE_KEY y SUPABASE_DB_URL.');
  console.error('SUPABASE_URL/NEXT_PUBLIC_SUPABASE_URL/VITE_SUPABASE_URL puede usarse para la URL del proyecto.');
  process.exit(1);
}

const supabase = createClient(supabaseUrl, serviceRoleKey, { auth: { persistSession: false } });
const sql = postgres(databaseUrl, { max: 1, prepare: false });

async function createSchema() {
  await sql.unsafe(`
    CREATE TABLE IF NOT EXISTS public.products (
      id text PRIMARY KEY,
      name text NOT NULL,
      brand text NOT NULL,
      category text NOT NULL,
      description text NOT NULL DEFAULT '',
      images text[] NOT NULL DEFAULT '{}',
      official_brand boolean NOT NULL DEFAULT false,
      official_product_url text,
      official_image_url text,
      price_source_url text,
      price_checked_at timestamptz,
      country text,
      city text,
      updated_at timestamptz NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS public.offers (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      product_id text NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
      store text NOT NULL,
      store_type text NOT NULL,
      country_code text NOT NULL,
      city_id text NOT NULL,
      price numeric(12, 2) NOT NULL,
      currency text NOT NULL,
      currency_symbol text NOT NULL,
      url text NOT NULL,
      in_stock boolean NOT NULL DEFAULT true,
      last_updated timestamptz,
      is_verified boolean NOT NULL DEFAULT false,
      store_address text,
      store_source_url text,
      physical_stock_verified boolean NOT NULL DEFAULT false,
      UNIQUE (product_id, store, country_code, city_id)
    );

    CREATE INDEX IF NOT EXISTS offers_product_id_idx ON public.offers(product_id);
    CREATE INDEX IF NOT EXISTS offers_country_code_idx ON public.offers(country_code);

    ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
    ALTER TABLE public.offers ENABLE ROW LEVEL SECURITY;

    DO $$ BEGIN
      CREATE POLICY "Public can read products" ON public.products FOR SELECT USING (true);
    EXCEPTION WHEN duplicate_object THEN NULL;
    END $$;

    DO $$ BEGIN
      CREATE POLICY "Public can read offers" ON public.offers FOR SELECT USING (true);
    EXCEPTION WHEN duplicate_object THEN NULL;
    END $$;
  `);
}

async function migrateData() {
  const productRows = products.map((product) => ({
    id: product.id,
    name: product.name,
    brand: product.brand,
    category: product.category,
    description: product.description,
    images: product.images,
    official_brand: product.officialBrand ?? false,
    official_product_url: product.officialProductUrl ?? null,
    official_image_url: product.officialImageUrl ?? null,
    price_source_url: product.priceSourceUrl ?? null,
    price_checked_at: product.priceCheckedAt ?? null,
    country: product.country ?? null,
    city: product.city ?? null,
    updated_at: new Date().toISOString(),
  }));

  const offerRows = offers.map((offer) => ({
    product_id: offer.productId,
    store: offer.store,
    store_type: offer.storeType,
    country_code: offer.countryCode,
    city_id: offer.cityId,
    price: offer.price,
    currency: offer.currency,
    currency_symbol: offer.currencySymbol,
    url: offer.url,
    in_stock: offer.inStock,
    last_updated: offer.lastUpdated,
    is_verified: offer.isVerified ?? false,
    store_address: offer.storeAddress ?? null,
    store_source_url: offer.storeSourceUrl ?? null,
    physical_stock_verified: offer.physicalStockVerified ?? false,
  }));

  for (let offset = 0; offset < productRows.length; offset += 100) {
    const { error } = await supabase.from('products').upsert(productRows.slice(offset, offset + 100), { onConflict: 'id' });
    if (error) throw new Error(`products: ${error.message}`);
  }

  for (let offset = 0; offset < offerRows.length; offset += 100) {
    const { error } = await supabase.from('offers').upsert(offerRows.slice(offset, offset + 100), { onConflict: 'product_id,store,country_code,city_id' });
    if (error) throw new Error(`offers: ${error.message}`);
  }

  return { products: productRows.length, offers: offerRows.length };
}

try {
  console.log(`Migrando catálogo a ${supabaseUrl}...`);
  await createSchema();
  const result = await migrateData();
  console.log(`Migración completada: ${result.products} productos y ${result.offers} ofertas.`);
} catch (error) {
  console.error('La migración falló:', error instanceof Error ? error.message : error);
  process.exitCode = 1;
} finally {
  await sql.end({ timeout: 5 });
}