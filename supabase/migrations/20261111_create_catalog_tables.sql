CREATE TABLE IF NOT EXISTS public.products (
  id text PRIMARY KEY,
  name text NOT NULL,
  brand text NOT NULL,
  category text NOT NULL,
  description text NOT NULL DEFAULT '',
  images text[] NOT NULL DEFAULT '{}',
  official_brand boolean NOT NULL DEFAULT false,
  official_product_url text,
  official_image_url text,
  price_source_url text,
  price_checked_at timestamptz,
  country text,
  city text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.offers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id text NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  store text NOT NULL,
  store_type text NOT NULL,
  country_code text NOT NULL,
  city_id text NOT NULL,
  price numeric(12, 2) NOT NULL,
  currency text NOT NULL,
  currency_symbol text NOT NULL,
  url text NOT NULL,
  in_stock boolean NOT NULL DEFAULT true,
  last_updated timestamptz,
  is_verified boolean NOT NULL DEFAULT false,
  store_address text,
  store_source_url text,
  physical_stock_verified boolean NOT NULL DEFAULT false,
  UNIQUE (product_id, store, country_code, city_id)
);

CREATE INDEX IF NOT EXISTS offers_product_id_idx ON public.offers(product_id);
CREATE INDEX IF NOT EXISTS offers_country_code_idx ON public.offers(country_code);

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.offers ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
  CREATE POLICY "Public can read products" ON public.products FOR SELECT USING (true);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE POLICY "Public can read offers" ON public.offers FOR SELECT USING (true);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;